let n = 0;
const r = (from, to, type, k, lag, short, explanation, precedent, extra = {}) => {
  const [fromId, fromStat] = from.split('.');
  const [toId, toStat] = to.split('.');
  return {
    id: 'r' + String(++n).padStart(3, '0'),
    fromId, fromStat, toId, toStat,
    domain: fromStat === toStat ? fromStat : `${fromStat}→${toStat}`,
    type, strengthMultiplier: k, lagTurns: lag, mode: 'pulse',
    short, explanation, precedent, canon: 'canon', ...extra,
  };
};
